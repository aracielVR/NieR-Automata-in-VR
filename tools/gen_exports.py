#!/usr/bin/env python3
"""Generates the d3d11.dll proxy export table.

Every export of the real d3d11.dll gets an assembly thunk that jumps to the real function.
D3D11CreateDevice and D3D11CreateDeviceAndSwapChain are implemented in C++ (d3d11_proxy.cpp) instead,
because that is where the mod hooks in.

Usage: gen_exports.py <d3d11.def from mingw-w64> <output dir>
"""
import os
import sys

WRAPPED = {"D3D11CreateDevice", "D3D11CreateDeviceAndSwapChain"}


def read_exports(def_path):
    names, in_exports = [], False
    for raw in open(def_path, encoding="utf-8"):
        line = raw.split(";")[0].strip()
        if not line:
            continue
        if line.upper() == "EXPORTS":
            in_exports = True
            continue
        if in_exports:
            name = line.split()[0].split("@")[0]
            if name not in names:
                names.append(name)
    return names


def main():
    def_path, out_dir = sys.argv[1], sys.argv[2]
    os.makedirs(out_dir, exist_ok=True)
    names = read_exports(def_path)
    thunked = [n for n in names if n not in WRAPPED]
    missing = WRAPPED - set(names)
    if missing:
        sys.exit(f"export list lacks {missing}")

    with open(os.path.join(out_dir, "exports.def"), "w", newline="\n") as f:
        f.write("LIBRARY d3d11.dll\nEXPORTS\n")
        for n in names:
            target = f"NVR_{n}" if n in WRAPPED else f"NVR_Thunk_{n}"
            f.write(f"    {n} = {target}\n")

    with open(os.path.join(out_dir, "export_names.inc"), "w", newline="\n") as f:
        f.write("// generated by tools/gen_exports.py - names of the thunked exports, in table order\n")
        for n in thunked:
            f.write(f'"{n}",\n')

    with open(os.path.join(out_dir, "thunks.S"), "w", newline="\n") as f:
        f.write("# generated by tools/gen_exports.py\n")
        f.write(".intel_syntax noprefix\n.text\n\n")
        for i, n in enumerate(thunked):
            f.write(f".globl NVR_Thunk_{n}\n.p2align 4\nNVR_Thunk_{n}:\n")
            f.write(f"    mov rax, qword ptr [rip + g_realProcs + {i * 8}]\n")
            f.write("    test rax, rax\n    jz 1f\n    jmp rax\n")
            f.write(f"1:  mov r11d, {i}\n    jmp NVR_ThunkSlow\n\n")
        # Slow path: first call before the real DLL is loaded. Preserve argument registers,
        # resolve everything, then continue into the real function.
        f.write(
            """.p2align 4
NVR_ThunkSlow:
    push rcx
    push rdx
    push r8
    push r9
    push r11
    sub rsp, 0x60
    movdqu xmmword ptr [rsp + 0x20], xmm0
    movdqu xmmword ptr [rsp + 0x30], xmm1
    movdqu xmmword ptr [rsp + 0x40], xmm2
    movdqu xmmword ptr [rsp + 0x50], xmm3
    call NVR_ResolveAll
    movdqu xmm0, xmmword ptr [rsp + 0x20]
    movdqu xmm1, xmmword ptr [rsp + 0x30]
    movdqu xmm2, xmmword ptr [rsp + 0x40]
    movdqu xmm3, xmmword ptr [rsp + 0x50]
    add rsp, 0x60
    pop r11
    pop r9
    pop r8
    pop rdx
    pop rcx
    lea rax, [rip + g_realProcs]
    mov rax, qword ptr [rax + r11 * 8]
    jmp rax
"""
        )
    print(f"{len(names)} exports ({len(thunked)} thunked, {len(WRAPPED)} wrapped)")


if __name__ == "__main__":
    main()
