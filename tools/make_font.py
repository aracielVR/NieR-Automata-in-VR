#!/usr/bin/env python3
"""Rasterises DejaVu Sans (ASCII 32-126) at two sizes into src/gen/font.h for the in-headset menu.
Each glyph: x, y, w, h in the atlas, x/y offset from the pen position (y from the baseline up to
the top of the line), and the advance. The atlas is 8-bit coverage."""
import sys
from PIL import Image, ImageDraw, ImageFont

FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
BOLD = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
SIZES = [("Body", FONT, 30), ("Small", FONT, 22), ("Title", BOLD, 36)]

def build(name, path, px):
    f = ImageFont.truetype(path, px)
    ascent, descent = f.getmetrics()
    lineh = ascent + descent
    glyphs, x, y, rowh, W = [], 1, 1, 0, 512
    tiles = []
    for c in range(32, 127):
        ch = chr(c)
        l, t, r, b = f.getbbox(ch)
        w, h = max(r - l, 0), max(b - t, 0)
        adv = round(f.getlength(ch))
        if x + w + 1 > W:
            x, y, rowh = 1, y + rowh + 1, 0
        tiles.append((ch, x, y, w, h, l, t, adv))
        x += w + 1
        rowh = max(rowh, h)
    H = y + rowh + 1
    img = Image.new("L", (W, H), 0)
    d = ImageDraw.Draw(img)
    for ch, gx, gy, w, h, l, t, adv in tiles:
        if w and h:
            d.text((gx - l, gy - t), ch, font=f, fill=255)
    out = [f"// {name}: {path.split('/')[-1]} {px}px, line height {lineh}, ascent {ascent}"]
    out.append(f"static const int k{name}W = {W}, k{name}H = {H}, k{name}Line = {lineh}, k{name}Ascent = {ascent};")
    out.append(f"static const short k{name}Glyph[95][7] = {{  // x, y, w, h, xoff, yoff(top below line top), advance")
    for ch, gx, gy, w, h, l, t, adv in tiles:
        out.append(f"    {{{gx}, {gy}, {w}, {h}, {l}, {t}, {adv}}},")
    out.append("};")
    data = img.tobytes()
    out.append(f"static const unsigned char k{name}Atlas[{W * H}] = {{")
    for i in range(0, len(data), 32):
        out.append("    " + ",".join(str(v) for v in data[i:i + 32]) + ",")
    out.append("};")
    return "\n".join(out)

parts = ["// Generated by tools/make_font.py from DejaVu Sans (Bitstream Vera / DejaVu license, see\n// FONT-LICENSE.txt). Do not edit.\n#pragma once"]
for n, p, s in SIZES:
    parts.append(build(n, p, s))
open(sys.argv[1], "w").write("\n".join(parts) + "\n")
